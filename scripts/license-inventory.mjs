// Generates THIRD_PARTY_NOTICES.md for the packages bundled into the Spoon app.
// All runtime code is bundled by electron-vite, so the shipped set is the transitive
// production dependency closure of the packages imported from src/ (ROOTS below).
// Usage: npm run licenses [-- --check]   (--check fails on licences outside ALLOWED)
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const ROOTS = [
  'react',
  'react-dom',
  'radix-ui',
  'lucide-react',
  'cmdk',
  'class-variance-authority',
  'clsx',
  'tailwind-merge',
  '@tanstack/react-virtual',
  'highlight.js',
  'zod',
  'tailwindcss',
  'tw-animate-css',
  'electron'
]
const ALLOWED = new Set([
  'MIT',
  'ISC',
  'BSD-2-Clause',
  'BSD-3-Clause',
  'Apache-2.0',
  '0BSD',
  'BlueOak-1.0.0',
  'CC0-1.0',
  'Unlicense'
])

function findPkgDir(name, from) {
  let dir = from
  for (;;) {
    const candidate = join(dir, 'node_modules', name)
    if (existsSync(join(candidate, 'package.json'))) return candidate
    const parent = dirname(dir)
    if (parent === dir) return null
    dir = parent
  }
}

const seen = new Map()
function visit(name, from) {
  const dir = findPkgDir(name, from)
  if (!dir || seen.has(dir)) return
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  seen.set(dir, pkg)
  // Electron's own runtime deps are only used by its npm installer, not shipped.
  if (name === 'electron') return
  for (const dep of Object.keys(pkg.dependencies ?? {})) visit(dep, dir)
  for (const dep of Object.keys(pkg.peerDependencies ?? {}))
    if (findPkgDir(dep, dir)) visit(dep, dir)
}
for (const r of ROOTS) visit(r, root)

const licenseText = (dir) => {
  const f = readdirSync(dir).find((n) => /^(licen[cs]e|copying)(\.|$)/i.test(n))
  return f ? readFileSync(join(dir, f), 'utf8').trim() : null
}
const licenseOf = (pkg) =>
  typeof pkg.license === 'string'
    ? pkg.license
    : (pkg.license?.type ?? (pkg.licenses ?? []).map((l) => l.type).join(' OR ')) || 'UNKNOWN'

const rows = [...seen.entries()]
  .map(([dir, pkg]) => ({
    dir,
    name: pkg.name,
    version: pkg.version,
    license: licenseOf(pkg),
    repo: typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url
  }))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))

const problems = rows.filter(
  (r) => !r.license.split(/\s+(?:OR|AND)\s+|[()]/).some((l) => ALLOWED.has(l.trim()))
)

let md = `# Third-party notices\n\nSpoon bundles the following open-source packages (generated by \`npm run licenses\`; do not edit by hand).\n`
md += `Electron additionally ships Chromium and Node.js licence texts as \`LICENSES.chromium.html\` and \`LICENSE.electron.txt\` next to the executable.\n\n`
md += `| Package | Version | Licence |\n| --- | --- | --- |\n`
for (const r of rows) md += `| ${r.name} | ${r.version} | ${r.license} |\n`
md += `\n## Licence texts\n`
const done = new Set()
for (const r of rows) {
  const key = `${r.name}@${r.version}`
  if (done.has(key)) continue
  done.add(key)
  const text = licenseText(r.dir)
  md += `\n### ${key}\n\n${r.repo ? `Source: ${r.repo.replace(/^git\+/, '')}\n\n` : ''}`
  md += text
    ? '```text\n' + text.replace(/```/g, "'''") + '\n```\n'
    : `Licence: ${r.license} (no licence file included in the package).\n`
}
writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), md)
console.log(`${rows.length} packages written to THIRD_PARTY_NOTICES.md`)
const counts = {}
for (const r of rows) counts[r.license] = (counts[r.license] ?? 0) + 1
console.log(counts)
if (problems.length) {
  console.log(
    'Licences needing review:',
    problems.map((p) => `${p.name}@${p.version} (${p.license})`).join(', ')
  )
  if (process.argv.includes('--check')) process.exit(1)
}
